using System.Collections.Concurrent;

namespace RealmDom.World;

/// <summary>Where real map features come from (OpenStreetMap via Overpass in development, an own extract in production).</summary>
public interface IMapSource
{
    Task<IReadOnlyList<MapFeature>> GetFeaturesAsync((double S, double W, double N, double E) bbox, CancellationToken ct);
}

/// <summary>Persistent world storage. Implementations must make <see cref="TryClaimCellAsync"/> atomic across servers.</summary>
public interface IWorldStore
{
    Task<CellStatus?> GetCellStatusAsync(string cellId, CancellationToken ct);
    /// <summary>
    /// Atomically marks a cell as "being generated by me". False if it is finished, or another server claimed it
    /// less than <see cref="WorldService.StaleClaim"/> ago (an older claim is from a crashed server and may be taken over).
    /// </summary>
    Task<bool> TryClaimCellAsync(string cellId, CancellationToken ct);
    Task SaveCellAsync(string cellId, IReadOnlyList<Landmark> landmarks, string mapVersion, CancellationToken ct);
    Task ReleaseCellAsync(string cellId, CancellationToken ct);
    Task<IReadOnlyList<Landmark>> GetLandmarksAsync(IReadOnlyCollection<string> cellIds, CancellationToken ct);
    Task<Landmark?> GetLandmarkAsync(string landmarkId, CancellationToken ct);
    Task<IReadOnlyDictionary<string, LandmarkState>> GetStatesAsync(IReadOnlyCollection<string> landmarkIds, string realm, CancellationToken ct);
    /// <summary>Saves only if the stored version still equals <paramref name="expectedVersion"/> (0 = never saved).</summary>
    Task<bool> TrySaveStateAsync(LandmarkState state, long expectedVersion, CancellationToken ct);
}

/// <summary>Which parts of the world are live. An empty list means everywhere (development).</summary>
public sealed class RegionPolicy
{
    public sealed record Region(string Name, IReadOnlyList<(double Lat, double Lon)> Polygon);
    public IReadOnlyList<Region> Regions { get; }
    public RegionPolicy(IEnumerable<Region>? regions = null) => Regions = (regions ?? []).ToList();
    public string? RegionOf(string cellId)
    {
        if (Regions.Count == 0) return "everywhere";
        var (lat, lon) = Cells.Center(cellId);
        return Regions.FirstOrDefault(r => Geo.Contains(r.Polygon, lat, lon))?.Name;
    }
    public bool IsLive(string cellId) => RegionOf(cellId) is not null;
}

public enum CellOutcome { Ready, NotLive, Unavailable }

public sealed record CellView(string CellId, CellOutcome Outcome);
public sealed record LandmarkView(Landmark Landmark, LandmarkState State);
public sealed record AreaView(string CenterCell, string Realm, IReadOnlyList<CellView> Cells, IReadOnlyList<LandmarkView> Landmarks);

public enum ActionResult { Ok, NotFound, NotAllowed, Conflict }
public sealed record ActionOutcome(ActionResult Result, LandmarkView? View = null, string? Reason = null);

/// <summary>
/// The one place that creates the world. A cell is generated the first time anyone looks at it,
/// exactly once, and stored; from then on every player reads the same landmarks.
/// </summary>
public sealed class WorldService(IWorldStore store, IMapSource maps, WorldGenerator generator, RegionPolicy regions, TimeProvider? clock = null)
{
    private readonly ConcurrentDictionary<string, SemaphoreSlim> _locks = new();
    private readonly SemaphoreSlim _mapFetch = new(1, 1);
    private readonly TimeProvider _clock = clock ?? TimeProvider.System;
    public static string MapVersionTag(DateTimeOffset now) => "osm-" + now.ToString("yyyy-MM-dd");
    public TimeSpan WaitForOtherServer { get; init; } = TimeSpan.FromSeconds(30);
    public static readonly TimeSpan StaleClaim = TimeSpan.FromMinutes(2);

    public async Task<IReadOnlyList<CellView>> EnsureCellsAsync(IReadOnlyList<string> cellIds, CancellationToken ct)
    {
        var results = new Dictionary<string, CellOutcome>();
        var mine = new List<string>();
        var held = new List<SemaphoreSlim>();
        try
        {
            foreach (var id in cellIds.Distinct().OrderBy(c => c, StringComparer.Ordinal)) // ordered locking: no deadlocks
            {
                if (await store.GetCellStatusAsync(id, ct) == CellStatus.Ready) { results[id] = CellOutcome.Ready; continue; }
                if (!regions.IsLive(id)) { results[id] = CellOutcome.NotLive; continue; }
                var gate = _locks.GetOrAdd(id, _ => new SemaphoreSlim(1, 1));
                await gate.WaitAsync(ct); held.Add(gate);
                var status = await store.GetCellStatusAsync(id, ct);
                if (status == CellStatus.Ready) results[id] = CellOutcome.Ready;
                else if (await store.TryClaimCellAsync(id, ct)) mine.Add(id);
                else results[id] = await WaitForOtherAsync(id, ct); // another server instance is generating it
            }

            if (mine.Count > 0)
            {
                try
                {
                    IReadOnlyList<MapFeature> features;
                    await _mapFetch.WaitAsync(ct); // one map download at a time, for all newly claimed cells together
                    try { features = await maps.GetFeaturesAsync(Cells.BoundingBox(mine), ct); }
                    finally { _mapFetch.Release(); }
                    var version = MapVersionTag(_clock.GetUtcNow());
                    foreach (var id in mine)
                    {
                        await store.SaveCellAsync(id, generator.Generate(id, features), version, ct);
                        results[id] = CellOutcome.Ready;
                    }
                }
                catch (Exception ex)
                {
                    // never leave a cell stuck as "generating": release what we did not finish
                    foreach (var id in mine.Where(id => !results.ContainsKey(id)))
                    {
                        await store.ReleaseCellAsync(id, CancellationToken.None);
                        results[id] = CellOutcome.Unavailable;
                    }
                    if (ex is OperationCanceledException && ct.IsCancellationRequested) throw;
                }
            }
        }
        finally { foreach (var g in held) g.Release(); }

        return cellIds.Distinct().Select(id => new CellView(id, results.TryGetValue(id, out var o) ? o : CellOutcome.Unavailable)).ToList();
    }

    private async Task<CellOutcome> WaitForOtherAsync(string cellId, CancellationToken ct)
    {
        var until = _clock.GetUtcNow() + WaitForOtherServer;
        while (_clock.GetUtcNow() < until)
        {
            await Task.Delay(200, ct);
            var s = await store.GetCellStatusAsync(cellId, ct);
            if (s == CellStatus.Ready) return CellOutcome.Ready;
            if (s is null) return CellOutcome.Unavailable; // the other server gave up; the client can retry
        }
        return CellOutcome.Unavailable;
    }

    public async Task<AreaView> GetAreaAsync(double lat, double lon, string realm, int ring, CancellationToken ct)
    {
        var center = Cells.Of(lat, lon);
        var views = await EnsureCellsAsync(Cells.Around(center, ring), ct);
        var ready = views.Where(v => v.Outcome == CellOutcome.Ready).Select(v => v.CellId).ToList();
        return new AreaView(center, realm, views, await ViewsAsync(await store.GetLandmarksAsync(ready, ct), realm, ct));
    }

    public async Task<IReadOnlyList<LandmarkView>> ViewsAsync(IReadOnlyList<Landmark> landmarks, string realm, CancellationToken ct)
    {
        var states = await store.GetStatesAsync(landmarks.Select(l => l.Id).ToList(), realm, ct);
        return landmarks.Select(l => new LandmarkView(l, states.TryGetValue(l.Id, out var s) ? s : DefaultState.For(l, realm))).ToList();
    }

    private async Task<(Landmark?, LandmarkState?)> LoadAsync(string landmarkId, string realm, CancellationToken ct)
    {
        var l = await store.GetLandmarkAsync(landmarkId, ct);
        if (l is null) return (null, null);
        var states = await store.GetStatesAsync([l.Id], realm, ct);
        return (l, states.TryGetValue(l.Id, out var s) ? s : DefaultState.For(l, realm));
    }

    /// <summary>
    /// A player (or team) takes a landmark. In the full game this is only called after the server has
    /// validated the battle or duel; here it enforces the ownership rules and the version check.
    /// </summary>
    public async Task<ActionOutcome> CaptureAsync(string landmarkId, string realm, PlayerRef leader, IReadOnlyList<PlayerRef>? allies, long expectedVersion, CancellationToken ct)
    {
        var (l, s) = await LoadAsync(landmarkId, realm, ct);
        if (l is null || s is null) return new(ActionResult.NotFound);
        if (s.Version != expectedVersion) return new(ActionResult.Conflict, new(l, s), "The landmark changed. Refresh and try again.");
        if (s.OwnerId == leader.PlayerId || s.Team.Any(t => t.PlayerId == leader.PlayerId)) return new(ActionResult.NotAllowed, new(l, s), "You already hold this landmark.");
        if (s.BossAlive && (allies is null || allies.Count == 0)) return new(ActionResult.NotAllowed, new(l, s), "A fortress can only be taken by a team.");
        if (s.Faction == leader.Faction && s.OwnerId is not null && !s.Corrupted) return new(ActionResult.NotAllowed, new(l, s), "Your own faction holds it. Reinforce it instead.");

        var members = new[] { leader }.Concat(allies ?? []).GroupBy(p => p.PlayerId).Select(g => g.First()).ToList();
        var team = members.Count > 1 ? members.Select(m => new TeamShare(m.PlayerId, m.Name, 1.0 / members.Count)).ToList() : new List<TeamShare>();
        var next = s with { OwnerId = leader.PlayerId, OwnerName = leader.Name, Faction = leader.Faction, Corrupted = false, BossAlive = false, Team = team, Version = s.Version + 1 };
        return await store.TrySaveStateAsync(next, s.Version, ct) ? new(ActionResult.Ok, new(l, next)) : new(ActionResult.Conflict, null, "Someone else changed it first.");
    }

    public async Task<ActionOutcome> BuildAsync(string landmarkId, string realm, string playerId, string structure, long expectedVersion, CancellationToken ct)
    {
        var (l, s) = await LoadAsync(landmarkId, realm, ct);
        if (l is null || s is null) return new(ActionResult.NotFound);
        if (!Structures.All.Contains(structure)) return new(ActionResult.NotAllowed, new(l, s), "Unknown structure.");
        if (s.Version != expectedVersion) return new(ActionResult.Conflict, new(l, s), "The landmark changed. Refresh and try again.");
        bool owner = s.OwnerId == playerId || s.Team.Any(t => t.PlayerId == playerId);
        if (!owner || s.Corrupted) return new(ActionResult.NotAllowed, new(l, s), "Only the land's owners can build here.");
        if (s.Builds.Contains(structure)) return new(ActionResult.NotAllowed, new(l, s), "Already built.");
        if (s.Builds.Count >= Structures.SlotsFor(l)) return new(ActionResult.NotAllowed, new(l, s), "No free slot.");
        var next = s with { Builds = [.. s.Builds, structure], Version = s.Version + 1 };
        return await store.TrySaveStateAsync(next, s.Version, ct) ? new(ActionResult.Ok, new(l, next)) : new(ActionResult.Conflict, null, "Someone else changed it first.");
    }
}
